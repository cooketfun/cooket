import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { toEventSelector, toFunctionSelector } from "viem";
import { abiSurface, goContracts } from "./abi-surface.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../../..");
const out = path.join(root, "contracts/out");
const sdkOutput = path.join(root, "packages/contracts-sdk/src/abi.generated.ts");
const goOutput = path.join(root, "apps/indexer/abi/selected.generated.json");

function stable(item) {
  const copy = { ...item };
  delete copy.internalType;
  const clean = (value) => Array.isArray(value) ? value.map(clean) : value && typeof value === "object"
    ? Object.fromEntries(Object.entries(value).filter(([key]) => key !== "internalType").map(([key, child]) => [key, clean(child)]))
    : value;
  return clean(copy);
}

function select(contract, spec) {
  const artifactPath = path.join(out, spec.artifact);
  if (!fs.existsSync(artifactPath)) throw new Error(`${contract}: missing Foundry artifact ${artifactPath}; run forge build first`);
  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
  if (!Array.isArray(artifact.abi)) throw new Error(`${contract}: artifact has no ABI array`);
  const selected = [];
  for (const [type, names] of [["function", spec.functions], ["event", spec.events]]) {
    for (const name of names) {
      const matches = artifact.abi.filter((item) => item.type === type && item.name === name);
      if (matches.length !== 1) throw new Error(`${contract}: selected ${type} ${name} has ${matches.length} artifact matches`);
      selected.push(stable(matches[0]));
    }
  }
  return selected;
}

const selected = Object.fromEntries(Object.entries(abiSurface).map(([contract, spec]) => [contract, select(contract, spec)]));
const exportNames = {
  CooketFactoryV3: "cooketFactoryAbi", CooketCurveV3: "cooketCurveAbi", CooketTokenV3: "cooketTokenV3Abi",
  GraduationManagerV3: "graduationManagerV3Abi", FeeManagerV3: "feeManagerV3Abi", CTORegistryV3: "ctoRegistryV3Abi",
  CTOTreasuryV3: "ctoTreasuryV3Abi", PermanentLPCustodianV3: "permanentLPCustodianV3Abi",
  PermanentLPFeeVaultV3: "permanentLPFeeVaultV3Abi",
  PermanentLPCustodianDeployerV3: "permanentLPCustodianDeployerV3Abi",
  GraduationSettlementExecutorV3: "graduationSettlementExecutorV3Abi",
};
let sdk = "// Generated by scripts/check-abi-parity.mjs --write from reviewed abi-surface.mjs.\n// Do not edit by hand. Foundry artifacts are required source inputs.\n\n";
for (const [contract, abi] of Object.entries(selected)) {
  sdk += `export const ${exportNames[contract]} = [\n${abi.map((item) => `  ${JSON.stringify(item)},`).join("\n")}\n] as const;\n\n`;
}
const go = `${JSON.stringify({ generatedBy: "packages/contracts-sdk/scripts/check-abi-parity.mjs", contracts: Object.fromEntries(goContracts.map((name) => [name, selected[name]])) })}\n`;

function verify(file, expected, label) {
  if (!fs.existsSync(file)) throw new Error(`${label}: missing generated consumer file ${file}; run pnpm --filter @cooket/contracts-sdk run generate-abi`);
  const actual = fs.readFileSync(file, "utf8");
  if (actual !== expected) {
    const actualLines = actual.split("\n");
    const expectedLines = expected.split("\n");
    const line = expectedLines.findIndex((value, index) => value !== actualLines[index]);
    throw new Error(`${label}: mismatch at line ${line + 1}\nexpected: ${expectedLines[line] ?? "<EOF>"}\nactual:   ${actualLines[line] ?? "<EOF>"}`);
  }
}

if (process.argv.includes("--write")) {
  fs.mkdirSync(path.dirname(goOutput), { recursive: true });
  fs.writeFileSync(sdkOutput, sdk);
  fs.writeFileSync(goOutput, go);
  console.log(`wrote ${path.relative(root, sdkOutput)} and ${path.relative(root, goOutput)}`);
} else {
  verify(sdkOutput, sdk, "SDK ABI parity");
  verify(goOutput, go, "Go ABI parity");
  const graduated = selected.CooketCurveV3.find((item) => item.type === "event" && item.name === "Graduated");
  if (graduated.inputs[3]?.name !== "nativeUsdcAmount") throw new Error("CooketCurveV3.Graduated input[3] must be nativeUsdcAmount");
  const exactCTOEvents = [
    "CTOTreasuryDeployed", "CTOProposed", "CTOAccepted", "CTOReady", "CTOCancelled", "CTOExpired", "CTOActivated",
    "CreatorFeeCheckpointed", "PendingCreatorPayoutInvalidated", "CTOFeeRouteActivated", "CheckpointedCreatorFeesClaimed",
    "CTOAcceptanceSubmitted", "SupportedAssetRegistered", "TreasuryAssetTransferred", "CreatorFeesPulled",
  ];
  const ctoItems = [...selected.CTORegistryV3, ...selected.FeeManagerV3, ...selected.CTOTreasuryV3];
  for (const name of exactCTOEvents) {
    if (!ctoItems.some((item) => item.type === "event" && item.name === name)) {
      throw new Error(`selected ABI is missing exact CTO event ${name}`);
    }
  }
  for (const invented of ["CheckpointedFeesClaimed", "PendingPayoutInvalidated"]) {
    if (ctoItems.some((item) => item.name === invented)) throw new Error(`selected ABI invented ${invented}`);
  }
  for (const [contract, abi] of Object.entries(selected)) {
    const selectors = new Map();
    for (const item of abi) {
      if (/weth/i.test(item.name) || JSON.stringify(item).toLowerCase().includes('"weth')) throw new Error(`${contract}.${item.name}: stale WETH ABI surface`);
      const selector = item.type === "function" ? toFunctionSelector(item) : toEventSelector(item);
      const previous = selectors.get(selector);
      if (previous) throw new Error(`${contract}: selector/topic collision ${selector} for ${previous} and ${item.name}`);
      selectors.set(selector, `${item.type} ${item.name}`);
    }
  }
  console.log(`ABI parity passed for ${Object.keys(selected).length} contracts, ${Object.values(selected).flat().filter((x) => x.type === "function").length} functions, and ${Object.values(selected).flat().filter((x) => x.type === "event").length} events.`);
}
